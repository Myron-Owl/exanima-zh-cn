"""Generate the native table from reviewed, exact-hash game version profiles."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HOOK_ORDER = ('draw', 'measure', 'label', 'batch', 'width', 'font_width',
              'center', 'clip', 'block', 'float_block', 'block_lines')
LAYOUT_FIELDS = ('font_slot', 'begin', 'end', 'uv', 'vertex', 'color',
                 'batch_count', 'gui_slot', 'current_color')


def address(value):
    result = int(value, 0) if isinstance(value, str) else int(value)
    if not 0 < result < 0x600000:
        raise ValueError(f'Invalid image address: {value!r}')
    return result


def render(profiles):
    output = ['/* Generated by tools/generate_version_profiles.py; edit data/versions.json. */',
              '#ifndef EXANIMA_ZH_VERSION_PROFILES_H', '#define EXANIMA_ZH_VERSION_PROFILES_H',
              '#include "unicode.h"', '#include <string.h>',
              '#define ZH_HOOK_COUNT 11',
              'typedef struct { uint32_t rva; unsigned char signature[24]; size_t size; } ZhHookSite;',
              'typedef struct { const char *id, *exe_sha256; ZhEngineLayout layout; ZhHookSite hooks[ZH_HOOK_COUNT]; } ZhGameVersion;']
    seen = set()
    if not profiles:
        raise ValueError('No game versions configured')
    for index, profile in enumerate(profiles):
        digest = profile['exe_sha256']
        if not re.fullmatch('[0-9a-f]{64}', digest) or digest in seen:
            raise ValueError('Invalid or duplicate executable SHA256')
        seen.add(digest)
        if not re.fullmatch('[a-zA-Z0-9_.-]+', profile['id']):
            raise ValueError('Version identifier must be a plain ASCII identifier')
        scopes = profile['scopes']
        if profile['remap_scopes'] and not scopes:
            raise ValueError('A remapped version needs explicit context addresses')
        for column in ('legacy_rva', 'current_rva'):
            values = [address(row[column]) for row in scopes]
            if len(values) != len(set(values)):
                raise ValueError('Context mappings must be one-to-one')
        if scopes:
            output.append(f'static const ZhScopeRva zh_scopes_{index}[] = {{')
            output += [f'    {{0x{address(row["legacy_rva"]):x},0x{address(row["current_rva"]):x}}},' for row in scopes]
            output.append('};')
    output.append('static const ZhGameVersion zh_game_versions[] = {')
    for index, profile in enumerate(profiles):
        output.append('    {')
        output.append(f'        .id="{profile["id"]}", .exe_sha256="{profile["exe_sha256"]}",')
        output.append('        .layout={')
        for key in LAYOUT_FIELDS:
            output.append(f'            .{key}=0x{address(profile["layout"][key]):x},')
        output.append(f'            .scopes={"zh_scopes_"+str(index) if profile["scopes"] else "NULL"},')
        output.append(f'            .scope_count={len(profile["scopes"])}, .remap_scopes={"TRUE" if profile["remap_scopes"] else "FALSE"}')
        output.append('        }, .hooks={')
        if tuple(row['name'] for row in profile['hooks']) != HOOK_ORDER:
            raise ValueError('Hook order must match the native replacement table')
        for row in profile['hooks']:
            signature = bytes.fromhex(row['signature'])
            if not 14 <= len(signature) <= 24:
                raise ValueError('Invalid trampoline copy length')
            values = ','.join(f'0x{value:02x}' for value in signature)
            output.append(f'            {{0x{address(row["rva"]):x},{{{values}}},{len(signature)}}}, /* {row["name"]} */')
        output += ['        }', '    },']
    output += ['};',
               'static inline const ZhGameVersion *zh_find_version(const char *sha256) {',
               '    for(size_t i=0;i<sizeof(zh_game_versions)/sizeof(zh_game_versions[0]);i++)',
               '        if(!strcmp(sha256,zh_game_versions[i].exe_sha256)) return zh_game_versions+i;',
               '    return NULL;', '}', '#endif', '']
    return '\n'.join(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Reject a stale generated header without rewriting it.')
    args = parser.parse_args()
    data = json.loads((ROOT / 'data/versions.json').read_text(encoding='utf-8'))
    content = render(data['versions']).encode('utf-8')
    header = ROOT / 'native/version_profiles.h'
    if args.check:
        if not header.is_file() or header.read_bytes() != content:
            raise SystemExit('Version header is stale; run tools/generate_version_profiles.py')
    elif not header.is_file() or header.read_bytes() != content:
        header.write_bytes(content)
    print(f'Verified {len(data["versions"])} exact-hash version profiles.')


if __name__ == '__main__':
    main()
